def chapter_exits(data, chapters, owner, ch, entries, limit=4000000):
    """Точный проход главы ch от каждого входа: все состояния на выходе (начало следующей главы / конец игры)."""
    sc = data['scenes']
    start = chapters[ch]['start']
    exits, seen, n = [], set(), 0
    stack = [(start, dict(e)) for e in entries]
    while stack:
        sid, f = stack.pop()
        key = (sid, tuple(sorted((k, v) for k, v in f.items() if v)))
        if key in seen:
            continue
        seen.add(key)
        n += 1
        if n > limit:
            raise RuntimeError('гл. %d: больше %d состояний' % (ch, limit))
        for b in sc[sid]['beats']:
            if 'if' in b and not A.cond_ok(b['if'], f):
                if b.get('else'):
                    stack.append((b['else'], f))
                    break
                continue
            if 'set' in b:
                f = dict(f)
                for k, v in b['set'].items():
                    f[k] = f.get(k, 0) + int(v)
            if 'choice' in b:
                for o in b['choice']['opts']:
                    if 'if' not in o or A.cond_ok(o['if'], f):
                        stack.append((o['go'], f))
                break
            if 'peek' in b:
                stack.append((b['yes'], f))
                stack.append((b['no'], f))
                break
            if 'qte' in b and b.get('fail'):
                ff = dict(f)
                if b['qte'] == 'brake':
                    ff['lamp'] = 1
                stack.append((b['fail'], ff))
            if b.get('go'):
                stack.append((b['go'], f))
                break
            if b.get('end'):
                exits.append(f)
                break
    return exits, n


