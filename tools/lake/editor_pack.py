def add_table(doc, rows, widths=None, head=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Light Grid Accent 1'
    if widths:   # ширина колонок — и в сетке таблицы (LibreOffice/PDF берут её, а не ширину ячеек)
        t.autofit = False
        for j, w in enumerate(widths):
            t.columns[j].width = Cm(w)
    for i, r in enumerate(rows):
        for j, c in enumerate(r):
            cell = t.cell(i, j)
            cell.text = ''
            p = cell.paragraphs[0]
            run = p.add_run(str(c))
            run.font.size = Pt(9.5)
            if head and i == 0:
                run.bold = True
            if widths:
                cell.width = Cm(widths[j])
    doc.add_paragraph()
    return t


