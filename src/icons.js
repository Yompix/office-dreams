function icoSVG(name, size, cls) {
  const rows = ICONS[name];
  if (!rows) return '';
  let rects = '';
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') { x++; continue; }
      let x2 = x + 1;
      while (x2 < row.length && row[x2] === ch) x2++;
      const fill = ch === '#' ? 'currentColor' : ICON_PAL[ch];
      rects += `<rect x="${x}" y="${y}" width="${x2 - x}" height="1" fill="${fill}"/>`;
      x = x2;
    }
  }
  const px = size || 18;
  return `<svg class="ico ${cls || ''}" viewBox="0 0 11 11" width="${px}" height="${px}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
if (typeof module !== 'undefined') module.exports = { ICONS, ICON_PAL, icoSVG };
